def derating(family: str,temp_c: float):
    pts=TEMPERATURE_DERATING[family]
    if temp_c<=pts[0][0]: return pts[0][1]
    if temp_c>=pts[-1][0]: return pts[-1][1]
    lo=int(temp_c)-pts[0][0]
    a,b=pts[lo],pts[lo+1]
    f=(temp_c-a[0])/(b[0]-a[0])
    return a[1]+f*(b[1]-a[1])
